// Bundles view/ into src/view-html.ts, the one file the driver imports to open the 3D view.
// Usage: node scripts/build-view.mjs [--check]

import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const OUTPUT = `${root}src/view-html.ts`;
const MAX_BYTES = 1_500_000;

export async function renderViewModule() {
    const result = await build({
        entryPoints: [`${root}view/main.ts`],
        bundle: true,
        minify: true,
        format: "iife",
        target: "es2022",
        write: false,
        logLevel: "silent",
    });
    const script = result.outputFiles[0].text.trim();
    if (/<\/script|<!--/i.test(script)) throw new Error("bundle contains a sequence that would end its <script> early");

    const shell = readFileSync(`${root}view/shell.html`, "utf8").trim();
    const [beforeBoot, afterBoot] = splitOnce(shell, "__BOOT__");
    const [beforeScript, afterScript] = splitOnce(afterBoot, "__SCRIPT__");

    const source = `// Generated by scripts/build-view.mjs from view/. Do not edit by hand. Run \`npm run build:view\`.
import type { ViewBoot } from "../shared/protocol";

const BEFORE_BOOT = ${JSON.stringify(beforeBoot)};
const AFTER_BOOT = ${JSON.stringify(beforeScript + script + afterScript)};

/** The 3D view as a complete HTML document for a floating iframe's srcDoc. */
export function buildViewHtml(boot: ViewBoot): string {
    return BEFORE_BOOT + inertJson(boot) + AFTER_BOOT;
}

/** JSON that cannot close its <script> element or start markup, whatever names and tokens it carries. */
function inertJson(value: unknown): string {
    return JSON.stringify(value).replace(/[<>&\\u2028\\u2029]/g, (c) => "\\\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}
`;
    const bytes = Buffer.byteLength(source);
    if (bytes > MAX_BYTES)
        throw new Error(`src/view-html.ts would be ${bytes} bytes, over the ${MAX_BYTES} byte budget`);
    return source;
}

function splitOnce(text, marker) {
    const at = text.indexOf(marker);
    if (at < 0 || text.indexOf(marker, at + 1) >= 0) throw new Error(`view/shell.html needs exactly one ${marker}`);
    return [text.slice(0, at), text.slice(at + marker.length)];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const source = await renderViewModule();
    if (process.argv.includes("--check")) {
        if (readFileSync(OUTPUT, "utf8") !== source) {
            console.error("src/view-html.ts is stale. Run npm run build:view.");
            process.exit(1);
        }
        console.log("src/view-html.ts is up to date");
    } else {
        writeFileSync(OUTPUT, source);
        console.log(`wrote src/view-html.ts (${Buffer.byteLength(source)} bytes)`);
    }
}
